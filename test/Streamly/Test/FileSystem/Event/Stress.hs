-- | Enable the events generated by listing a directory, on the platforms that
-- have them. On Linux, listing a directory then generates 8 events.
touchEvents :: Config -> Config
#if defined(CABAL_OS_LINUX)
touchEvents =
      Linux.setOpened True
    . Linux.setAccessed True
    . Linux.setNonWriteClosed True
#else
touchEvents = id
#endif

noRestart :: Config -> Config
#if defined(CABAL_OS_LINUX)
noRestart = Linux.setRestartOnOverflow False
#else
noRestart = id
#endif

-- | The overflow event is parsed from an uninitialized buffer on Windows on
-- this branch.
--
-- XXX Run the overflow tests on Windows when the fix on the
-- windows-robustness branch is merged.
overflowSkip :: Maybe String
overflowSkip
    | isWindows = Just "enable when windows-robustness is merged"
    | otherwise = Nothing

say :: String -> IO ()
say msg = putStrLn ("  " ++ msg) >> hFlush stdout

-- | Run a test in a new temporary directory, with a time limit.
withBase :: Int -> (FilePath -> IO ()) -> IO ()
withBase seconds action = do
    r <- timeout (seconds * 1000000)
        $ withSystemTempDirectory "fsevent_stress" action
    when (r == Nothing) $ expectationFailure "timed out"

-- | Create @n@ files named @prefix@ followed by a number.
createFiles :: FilePath -> String -> Int -> IO ()
createFiles dir prefix n =
    forM_ [1 .. n] $ \i -> createFile (dir </> (prefix ++ show i))

-- | Check the probes, and that the stream has not ended.
checkTree :: Watch -> IO ()
checkTree w = do
    r <- probeTree w "final"
    say $ show r
    ended <- streamEnded w
    ended `shouldSatisfy` (== Nothing) . fmap (either show show)
    probeOk r `shouldBe` True

-- | Number of overflows: at least @n@ on Linux, printed elsewhere.
checkLost :: Int -> Int -> IO ()
checkLost atLeast n = do
    say $ "isEventsLost events: " ++ show n
    when isLinux $ n `shouldSatisfy` (>= atLeast)

-------------------------------------------------------------------------------
-- Overflow at the start and after a burst
-------------------------------------------------------------------------------

data Outcome =
      Yes
    | No
    | Failed String -- ^ The test could not determine the outcome.
    | Skipped String -- ^ The test does not apply in this environment.
    deriving (Eq, Show)

-- | A scenario that overflows the event queue. The outcome is computed from
-- the number of 'isEventsLost' events seen 8 seconds and 10 seconds after
-- the scenario has run.
data Overflow = Overflow
    { title :: String
    , config :: Config -> Config
    -- | Use more directories than the queue can hold the events of.
    , largeTree :: Bool
    -- | Create more files than the queue can hold while the consumer is
    -- blocked. Otherwise only the watch itself generates events.
    , burst :: Bool
    , judge :: Int -> Int -> Outcome
    , expected :: Outcome
    }

-- | The number of directories in a large tree, in a small tree, and the
-- number of files in a burst. On Linux, listing a directory with the open,
-- access and close events enabled generates 8 events. The large tree
-- generates more events than the queue holds if it is listed that way, the
-- small tree generates fewer. 'Nothing' if the queue limit is too high.
overflowSizes :: IO (Maybe (Int, Int, Int))
overflowSizes = do
    queued <- queuedEventsLimit
    return
        $ if queued > 100000
          then Nothing
          else
            if isLinux
            then Just
                (queued `div` 8 + 500, queued `div` 8 - 500, queued + 1000)
            else Just (6000, 6000, queued)

noOverflow :: Outcome
noOverflow
    | isLinux = Failed "no overflow occurred"
    | otherwise = Skipped "no overflow occurred"

-- | 'Yes' if the 'isEventsLost' events have stopped.
judgeStopped :: Int -> Int -> Outcome
judgeStopped n1 n2
    | n2 == 0 = noOverflow
    | n2 > n1 = No
    | otherwise = Yes

-- | 'Yes' if there is one 'isEventsLost' event, 'No' if there are none.
judgeOnce :: Int -> Int -> Outcome
judgeOnce n1 n2
    | n2 == 0 = No
    | n1 == 1 && n2 == 1 = Yes
    | otherwise = Failed ("isEventsLost events: " ++ show (n1, n2))

runOverflow :: Overflow -> FilePath -> IO Outcome
runOverflow Overflow{..} base =
    overflowSizes >>= maybe tooHigh run

    where

    tooHigh = return (Skipped "max_queued_events is too high")

    run (large, small, files) = do
        let root = base </> "root"
            dirs = if largeTree then large else small
        budget <- dirBudget (stressBudget dirs 2 files) base
        if budget < dirs
        then return (Skipped "the limits do not allow the test")
        else do
            createDirectory root
            forM_ [1 .. dirs] $ \i ->
                createDirectory (root </> ("d" ++ show i))
            w <- startWatch config False root
            when burst $ do
                pause w "burst"
                createFiles root "f" files
                resume w
            threadDelay 8000000
            n1 <- lostCount w
            threadDelay 2000000
            n2 <- lostCount w
            r <- streamEnded w
            stopWatch w
            say $ "isEventsLost events: " ++ show n1 ++ " at 8s, "
                ++ show n2 ++ " at 10s"
            return $ case r of
                Just (Left e) -> Failed (show (e :: SomeException))
                Just (Right ()) -> Failed "the stream ended"
                Nothing -> judge n1 n2

overflowCases :: [Overflow]
overflowCases =
    [ Overflow
        { title = "the scan at the start of a watch overflows the queue"
        , config = touchEvents
        , largeTree = True
        , burst = False
        , judge = judgeOnce
        , expected = No
        }
    , Overflow
        { title = "isEventsLost events stop after a burst of events"
        , config = id
        , largeTree = True
        , burst = True
        , judge = judgeStopped
        , expected = Yes
        }
    ]
#if defined(CABAL_OS_LINUX)
    -- The files are created while the consumer is paused, the kernel queues
    -- one overflow event and drops the rest of the burst, and the restart
    -- generates no events, so exactly one 'isEventsLost' is expected.
    -- 'judgeStopped' would also pass if the restart overflowed the queue a
    -- few times before stopping. The case for all platforms above keeps
    -- 'judgeStopped', on macOS and Windows the number of overflows varies.
    ++
    [ Overflow
        { title = "restart: one overflow after a burst in a large tree"
        , config = touchEvents
        , largeTree = True
        , burst = True
        , judge = judgeOnce
        , expected = Yes
        }
    , Overflow
        { title = "restart: one overflow after a burst in a small tree"
        , config = touchEvents
        , largeTree = False
        , burst = True
        , judge = judgeOnce
        , expected = Yes
        }
    , Overflow
        { title = "no restart: one overflow after a burst"
        , config = noRestart
        , largeTree = True
        , burst = True
        , judge = judgeOnce
        , expected = Yes
        }
    ]
#endif

-- | The outcome is asserted on Linux only. The library has no restart on
-- macOS and Windows, and an overflow is not certain there.
overflowSpec :: Overflow -> Spec
overflowSpec o =
    it (title o) $ case overflowSkip of
        Just reason -> pendingWith reason
        Nothing -> withBase 300 $ \base -> do
            outcome <- runOverflow o base
            say $ "outcome: " ++ show outcome
            case outcome of
                Skipped reason -> pendingWith reason
                Failed reason -> expectationFailure reason
                _ -> when isLinux $ outcome `shouldBe` expected o

-------------------------------------------------------------------------------
-- A tree created as fast as possible
-------------------------------------------------------------------------------

-- | The fanout of the generated tree.
genFanout :: Int
genFanout = 4

-- | The files created in each directory of the generated tree.
genFiles :: Int
genFiles = 2

-- | The largest depth of a generated tree of at most @n@ directories.
genDepth :: Int -> Int
genDepth n = length (takeWhile (<= n) (scanl1 (+) levels)) - 1

    where

    levels = iterate (* genFanout) 1

-- | The paths of a tree of the given depth under @dir@, depth first, a
-- directory before its files and subdirectories. 'True' for a directory.
genPaths :: FilePath -> Int -> [(FilePath, Bool)]
genPaths dir depth =
    (dir, True)
        : [(dir </> ("f" ++ show i), False) | i <- [1 .. genFiles]]
        ++ concat
            [ genPaths (dir </> ("g" ++ show i)) (depth - 1)
            | depth > 0, i <- [1 .. genFanout]
            ]

genCreate :: (FilePath, Bool) -> IO ()
genCreate (path, isDir) =
    if isDir then createDirectory path else createFile path

-- | Create a tree under the root, with no delay between the operations. If
-- @blocked@, block the consumer after the first quarter of the tree, create
-- the rest of the tree and more files than the event queue holds, then
-- resume the consumer.
generatedTree :: Bool -> FilePath -> IO ()
generatedTree blocked base = do
    let root = base </> "root"
    createDirectory root
    queued <- queuedEventsLimit
    -- A directory, its files and its probe, and the files of a burst.
    budget <-
        dirBudget (stressBudget 22000 (genFiles + 2) (queued + 1000)) base
    let depth = genDepth budget
        paths = genPaths (root </> "g") depth
        (first, rest) = splitAt (length paths `div` 4) paths
    if depth < 3
    then pendingWith "the limits do not allow the test"
    else do
        say $ "directories: " ++ show (length (filter snd paths))
            ++ ", files: " ++ show (length (filter (not . snd) paths))
        w <- startWatch id (not blocked) root
        t0 <- getMonotonicTime
        if blocked
        then do
            mapM_ genCreate first
            pause w "generate"
            mapM_ genCreate rest
            createFiles root "burst" (queued + 1000)
            resume w
        else mapM_ genCreate paths
        t1 <- getMonotonicTime
        say $ "created in " ++ show (t1 - t0) ++ " s"
        n <- settledLost w "generated"
        t2 <- getMonotonicTime
        say $ "events read in " ++ show (t2 - t0) ++ " s"
        if blocked
        then checkLost 1 n
        else say $ "isEventsLost events: " ++ show n
        -- Without an overflow every path created is reported.
        unless (blocked || n > 0) $ do
            reported <- readIORef (created w)
            let missing =
                    filter (not . (`Set.member` reported)) (map fst paths)
            say $ "paths not reported: " ++ show (length missing)
            take 5 missing `shouldBe` []
        checkTree w
        stopWatch w

generatedTreeSpecs :: Spec
generatedTreeSpecs = do
    it "a tree created as fast as possible is watched completely"
        $ withBase 600 (generatedTree False)
    it "a tree created with the consumer blocked is watched after overflow"
        $ maybe (withBase 600 (generatedTree True)) pendingWith overflowSkip

-------------------------------------------------------------------------------
-- Changes to the tree during an overflow
-------------------------------------------------------------------------------

-- | A tree under @root/t@ of @n@ directories, and a tree @out/in@ of 50
-- directories outside the root.
setupTrees :: FilePath -> Int -> IO (FilePath, FilePath)
setupTrees base n = do
    let root = base </> "root"
        out = base </> "out"
    createDirectory root
    createDirectory out
    mapM_ (createDirectory . (root </>)) (treePaths "t" n)
    mapM_ (createDirectory . (out </>)) (treePaths "in" 50)
    return (root, out)

-- | Change the tree created by 'setupTrees': create a new subtree, rename a
-- directory within the tree and move one to another parent, move a
-- directory out and one in, delete a directory, and create directories in
-- many places.
changeTree :: FilePath -> FilePath -> IO ()
changeTree root out = do
    let t = root </> "t"
    createDirectoryIfMissing True (t </> "d0/new/a/b/c")
    createFile (t </> "d0/new/a/b/c/file")
    renameDirectory (t </> "d1") (t </> "d1r")
    renameDirectory (t </> "d2/d0") (t </> "d3/moved")
    renameDirectory (t </> "d4") (out </> "d4")
    renameDirectory (out </> "in") (t </> "d5/in")
    removePathForcibly (t </> "d6/d0")
    forM_ [0 .. 19 :: Int] $ \k ->
        createDirectoryIfMissing True
            (t </> "d7" </> ("d" ++ show (k `mod` 10))
                </> ("n" ++ show k) </> "x/y")

overflowChanges :: FilePath -> IO ()
overflowChanges base = do
    queued <- queuedEventsLimit
    budget <- dirBudget (stressBudget 2000 2 (queued + 1000)) base
    if budget < 2000
    then pendingWith "the limits do not allow the test"
    else do
        (root, out) <- setupTrees base 2000
        w <- startWatch id False root
        pause w "changes"
        createFiles root "burst" (queued + 1000)
        changeTree root out
        resume w
        n <- settledLost w "changes"
        checkLost 1 n
        checkTree w
        stopWatch w

-------------------------------------------------------------------------------
-- Overflows that repeat while the tree changes
-------------------------------------------------------------------------------

-- | Change the tree as fast as possible until the deadline, without using
-- more inodes over time: create and delete files in the root, create and
-- delete a subtree in turn under each of @t/d0@ to @t/d7@, rename @t/d9@ to
-- @t/d9r@ and back, and move @t/d8/d0@ out of the tree and back in. Returns
-- the number of rounds.
churn :: FilePath -> FilePath -> Double -> IO Int
churn root out deadline = go 0

    where

    t = root </> "t"

    toggle a b = do
        exists <- doesDirectoryExist a
        if exists then renameDirectory a b else renameDirectory b a

    go i = do
        now <- getMonotonicTime
        if now >= deadline
        then return i
        else do
            let files = [root </> ("c" ++ show j) | j <- [1 .. 1000 :: Int]]
                x = t </> ("d" ++ show (i `mod` 8)) </> "x"
            mapM_ createFile files
            mapM_ removeFile files
            removePathForcibly x
            createDirectoryIfMissing True (x </> "a/b")
            createFile (x </> "a/b/f")
            toggle (t </> "d9") (t </> "d9r")
            toggle (t </> "d8/d0") (out </> "d8d0")
            go (i + 1)

-- | Block the consumer, overflow the queue, then change a tree of at most
-- @dirs@ directories for 10 seconds while the consumer reads. On Linux, each
-- overflow restarts the watch, and the changes during a restart cause
-- another overflow. On Linux, at least @atLeast@ overflows are required.
cascade :: Int -> Int -> FilePath -> IO ()
cascade atLeast dirs base = do
    queued <- queuedEventsLimit
    budget <- dirBudget (stressBudget dirs 3 (queued + 2000)) base
    if budget < 2000
    then pendingWith "the limits do not allow the test"
    else do
        (root, out) <- setupTrees base budget
        say $ "directories: " ++ show budget
        w <- startWatch id False root
        pause w "cascade"
        createFiles root "burst" (queued + 1000)
        done <- newEmptyMVar
        deadline <- (+ 10) <$> getMonotonicTime
        _ <- forkIO (try (churn root out deadline) >>= putMVar done)
        resume w
        r <- takeMVar done
        case r of
            Left (e :: SomeException) -> expectationFailure (show e)
            Right rounds -> say $ "rounds of changes: " ++ show rounds
        n <- settledLost w "cascade"
        checkLost atLeast n
        checkTree w
        stopWatch w

-------------------------------------------------------------------------------
-- Main
-------------------------------------------------------------------------------

main :: IO ()
main = hspec $ describe moduleName $ do
    mapM_ overflowSpec overflowCases
    generatedTreeSpecs
    it "the tree is watched after changes during an overflow"
        $ maybe (withBase 600 overflowChanges) pendingWith overflowSkip
    it "the tree is watched after overflows that repeat while it changes"
        $ maybe (withBase 600 (cascade 2 10000)) pendingWith overflowSkip
    -- A restart of a tree of 2000 directories takes less time than one of
    -- 10000 directories, more overflows follow each other. On Linux, the
    -- IN_IGNORED events of the removal markers are dropped by the next
    -- overflow, and the markers accumulate. On a fast machine the restart
    -- of the small tree can finish before the queue fills again, only one
    -- overflow is required.
    it "a small tree is watched after overflows that repeat while it changes"
        $ maybe (withBase 600 (cascade 1 2000)) pendingWith overflowSkip
